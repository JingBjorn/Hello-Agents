# 初始执行提示词 (Execution Prompt) ：
# 这是智能体首次尝试解决问题的提示词，内容相对直接，只要求模型完成指定任务。
INITIAL_PROMPT_TEMPLATE = """
你是一位资深的Python程序员。请根据以下要求，编写一个Python函数。
你的代码必须包含完整的函数签名、文档字符串，并遵循PEP 8编码规范。

要求: {task}

请直接输出代码，不要包含任何额外的解释。
"""


# 反思提示词 (Reflection Prompt) ：这个提示词是 Reflection 机制的灵魂。
# 它指示模型扮演“代码评审员”的角色，对上一轮生成的代码进行批判性分析，并提供具体的、可操作的反馈。
REFLECT_PROMPT_TEMPLATE = """
你是一位极其严格的代码评审专家和资深算法工程师，对代码的性能有极致的要求。
你的任务是审查以下Python代码，并专注于找出其在<strong>算法效率</strong>上的主要瓶颈。

# 原始任务:
{task}

# 待审查的代码:
```python
{code}
```

审查代码的正确性、时间复杂度、空间复杂度和明显的实现开销。
仅提出与原始需求相关、具体可执行且收益合理的改进。

只输出 JSON：
- decision：只能是 CONTINUE 或 STOP。
- reason：说明决策依据。
- improvements：具体改进建议数组。

存在值得实施的改进时，decision 必须为 CONTINUE。
没有发现此类改进时，decision 才能为 STOP，且 improvements 必须为空数组。

算法复杂度接近最优，不等于实现无需改进。
请直接输出你的反馈，不要包含任何额外的解释。
"""


